"""skel_bench50.py — the FROZEN 50-frame skeleton benchmark.

Fixed set of 50 frames (image + human-GT mask), model masks generated by the deployed seg model.
All skeleton-accuracy iteration targets THIS set. Renders side-by-side BEFORE (original skeletonizer
defaults) vs AFTER (current tuned defaults) full-skeleton overlays on the model masks, plus counts.
Writes: data/skel_bench50/frames.json (frozen list), overlays + summary.json + chart -> data/skel_diag.

Usage: venv/bin/python3 src/skel_bench50.py
"""
import sys, json, math
from pathlib import Path
import cv2
import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE)); sys.path.insert(0, str(HERE / "skeleton"))
import skeleton as SK
from segment_octopus import OctoSegmenter
from seg_skeleton_pipeline import DEFAULT_CKPT

OUT = HERE.parent / "data" / "skel_diag"
BENCH = HERE.parent / "data" / "skel_bench50"
DS = HERE.parent / "data" / "dataset_seg_human"
SMOOTHS = [0.45, 0.65, 0.90]

BEFORE = {"bin_thresh": 112, "width_factor": 0.55,
          "floor_scale": 4.0, "floor_med": 0.40, "prefix_max": 0.58}
AFTER = {"bin_thresh": 96, "width_factor": 0.35,
         "floor_scale": 2.5, "floor_med": 0.30, "prefix_max": 0.70}


def skeleton_paths(mask255, cfg):
    """Full-res arm paths [(N,2) xy arrays] for a mask under a given config (best over smoothings)."""
    best = None
    for sm in SMOOTHS:
        try:
            small, sx, sy = SK.prepare_mask(mask255, 1024, sm, bin_thresh=cfg["bin_thresh"])
            dt = cv2.distanceTransform(small, cv2.DIST_L2, cv2.DIST_MASK_PRECISE)
            skel = SK.zhang_suen_thinning(small)
            skel = SK.remove_tiny_spurs(skel, dt, passes=2, width_factor=cfg["width_factor"])
            pts, adj, _ = SK.pixel_graph(skel)
            if len(pts) < 20:
                continue
            root = SK.choose_anatomical_root(pts, adj, dt, small)
            geod, parent = SK.dijkstra_tree(pts, adj, root, dt)
            try:
                paths = SK.select_arm_paths(pts, adj, root, parent, geod, dt, 1, 8,
                                            floor_scale=cfg["floor_scale"],
                                            floor_med=cfg["floor_med"],
                                            prefix_max=cfg["prefix_max"])
            except Exception:
                paths = []
            xy = [np.column_stack([pts[p, 1] * sx, pts[p, 0] * sy]) for p in paths]
            if best is None or len(xy) > len(best):
                best = xy
        except Exception:
            continue
    return best or []


def draw(img, mask255, paths, title, color_title):
    vis = cv2.addWeighted(img, 0.6, np.zeros_like(img), 0.4, 0)
    mm = mask255 > 0
    vis[mm] = (0.72 * vis[mm] + 0.28 * np.array([60, 150, 60])).astype(np.uint8)
    for a, p in enumerate(paths, 1):
        col = tuple(int(v) for v in SK.branch_color(a)[::-1])
        cv2.polylines(vis, [np.rint(p).astype(np.int32).reshape(-1, 1, 2)], False, col, 2, cv2.LINE_AA)
        tip = p[-1]
        cv2.circle(vis, (int(tip[0]), int(tip[1])), 6, (0, 215, 255), -1, cv2.LINE_AA)
    if len(paths):
        r = paths[0][0]
        cv2.circle(vis, (int(r[0]), int(r[1])), 8, (0, 0, 255), -1, cv2.LINE_AA)
    cv2.rectangle(vis, (0, 0), (vis.shape[1], 30), (0, 0, 0), -1)
    cv2.putText(vis, f"{title}: {len(paths)} arms", (6, 21), cv2.FONT_HERSHEY_SIMPLEX, 0.65,
                color_title, 2)
    return vis


def main():
    OUT.mkdir(parents=True, exist_ok=True); BENCH.mkdir(parents=True, exist_ok=True)
    frozen = BENCH / "frames.json"
    if frozen.exists():
        frames = json.load(open(frozen))
        print(f"using FROZEN benchmark ({len(frames)} frames)")
    else:
        rowsm = [json.loads(l) for l in open(DS / "manifest.jsonl") if l.strip()]
        rowsm = [r for r in rowsm if r.get("source") == "human" and r.get("image")]
        idx = np.linspace(0, len(rowsm) - 1, 50).astype(int)
        frames = [{"image": rowsm[int(i)]["image"], "mask": rowsm[int(i)]["mask"],
                   "clip": rowsm[int(i)]["clip"]} for i in idx]
        json.dump(frames, open(frozen, "w"), indent=1)
        print(f"FROZE benchmark: 50 frames -> {frozen}")

    S = OctOS = OctoSegmenter(str(DEFAULT_CKPT))
    nb, na, rows_ui = [], [], []
    for j, f in enumerate(frames):
        img = cv2.imread(str(DS / f["image"]))
        mm, _ = S.segment(img)
        m255 = (mm.astype(np.uint8)) * 255
        pb = skeleton_paths(m255, BEFORE)
        pa = skeleton_paths(m255, AFTER)
        nb.append(len(pb)); na.append(len(pa))
        left = draw(img, m255, pb, "BEFORE (original defaults)", (100, 160, 255))
        right = draw(img, m255, pa, "AFTER (tuned A-C)", (120, 255, 120))
        gap = np.full((left.shape[0], 6, 3), 45, np.uint8)
        cv2.imwrite(str(OUT / f"{j:03d}.jpg"), np.hstack([left, gap, right]),
                    [cv2.IMWRITE_JPEG_QUALITY, 87])
        rows_ui.append({"file": f"{j:03d}.jpg", "left_arms": len(pb), "right_arms": len(pa)})
        print(f"  [{j+1}/{len(frames)}] before {len(pb)} -> after {len(pa)}", flush=True)

    nb, na = np.array(nb), np.array(na)
    json.dump({"meta": {"title": "Frozen 50-frame benchmark — BEFORE vs AFTER (model masks)",
                        "left": "before arms", "right": "after arms"},
               "rows": rows_ui}, open(OUT / "summary.json", "w"), indent=1)
    import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(9, 4.4), facecolor="#111"); ax.set_facecolor("#111")
    bins = np.arange(-0.5, 9.5, 1)
    ax.hist(nb, bins=bins, alpha=.65, label=f"BEFORE (mean {nb.mean():.2f})", color="#ff7a5c")
    ax.hist(na, bins=bins, alpha=.65, label=f"AFTER (mean {na.mean():.2f})", color="#7ed47e")
    ax.set_xlabel("arms per frame (model masks, frozen 50)", color="#ccc")
    ax.set_ylabel("# frames", color="#ccc"); ax.tick_params(colors="#aaa")
    ax.set_title("Skeleton accuracy: before vs after Phases A-C", color="#eee")
    ax.legend(facecolor="#222", labelcolor="#ddd")
    plt.tight_layout()
    plt.savefig(OUT / "chart.png", dpi=130, facecolor="#111")
    plt.savefig(HERE.parent / "results" / "segmentation" / "skel_bench50_beforeafter.png",
                dpi=130, facecolor="#111")
    print(f"\nBEFORE mean {nb.mean():.2f} -> AFTER mean {na.mean():.2f}  (+{na.mean()-nb.mean():.2f})")


if __name__ == "__main__":
    main()
